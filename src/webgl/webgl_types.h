/// One getTexParameter answer: an integer (enums included), a float or a
/// boolean, as the parameter is typed.
struct TexParameterValue {
    GLint i = 0;
    GLfloat f = 0.0f;
    enum class Kind : uint8_t { Int, Float, Bool } kind = Kind::Int;
};

/// One getUniform / getVertexAttrib answer: `count` 32-bit words of one
/// kind, a scalar unless `array` (then the typed array or boolean sequence
/// the IDL names). A Buffer answer is a buffer name, 0 for null.
struct GLValue {
    enum class Kind : uint8_t { Float, Int, Uint, Bool, Buffer } kind = Kind::Int;
    bool array = false;
    uint32_t count = 1;
    uint32_t words[16]{};
};

