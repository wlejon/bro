// Node modules in an ES module script (the top-level await below makes this
// file one): exactly what test_node_modules_classic.js asserts for a classic
// script. fs, path and child_process come from require(), which a module
// script has too; none of them is a bare global, and a bare `fs` is a loud
// ReferenceError. `import fs from 'node:fs'` is not an alternative: bronze
// resolves no builtin module specifiers, and rejects the script at compile
// time (docs/brokit-api.js).

await Promise.resolve();

assert(typeof require === 'function', 'a module script has require()');
for (const name of ['fs', 'path', 'child_process']) {
    const mod = require(name);
    assert(mod && typeof mod === 'object', "require('" + name + "') is an object");
    assert(require('node:' + name) === mod, "require('node:" + name + "') is require('" + name + "')");
    assert(globalThis[name] === undefined, name + ' is not a property of globalThis');
}
assert(typeof fs === 'undefined', 'typeof fs is undefined');
assert(typeof path === 'undefined', 'typeof path is undefined');
assert(typeof child_process === 'undefined', 'typeof child_process is undefined');

let threw = null;
try { fs.existsSync('.'); } catch (e) { threw = e; }
assert(threw instanceof ReferenceError, 'a bare fs throws a ReferenceError, got ' + threw);
assert(/\bfs\b/.test(String(threw && threw.message)), 'the ReferenceError names fs: ' + threw);

const fsm = require('fs');
assert(fsm.existsSync('.'), "require('fs') works after an await");
assert(typeof os === 'object' && os === require('os'), 'os is a global and is require(\'os\')');

console.log('test_node_modules_module: OK');
